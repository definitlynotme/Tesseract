def localized_territory_name(country_code: object, language: object) -> str:
    """Return a CLDR territory name without guessing from provider prose."""

    code = str(country_code or "").strip().upper()
    if re.fullmatch(r"[A-Z]{2}", code) is None or code == "ZZ":
        return ""
    if Locale is None:
        return ""
    requested = str(language or "").strip()
    normalized = LANGUAGE_ALIASES.get(requested.casefold(), requested.replace("-", "_"))
    if normalized not in SUPPORTED_LANGUAGES:
        normalized = DEFAULT_LANGUAGE
    try:
        locale = Locale.parse(normalized, sep="_")
    except (UnknownLocaleError, ValueError, TypeError):
        return ""
    return str(locale.territories.get(code) or "").strip()


