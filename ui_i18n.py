def _translation_resource_root() -> Path:
    if getattr(sys, "frozen", False) and hasattr(sys, "_MEIPASS"):
        return Path(str(sys._MEIPASS)).resolve()
    return Path(__file__).resolve().parent


def _load_translation_overlays() -> dict[str, dict[str, str]]:
    locale_dir = _translation_resource_root() / "locales"
    overlays: dict[str, dict[str, str]] = {}
    for language in SUPPORTED_LANGUAGES:
        if language in {SOURCE_LANGUAGE, "en_US"}:
            continue
        path = locale_dir / f"{language}.json"
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            payload = {}
        if isinstance(payload, dict):
            overlays[language] = {
                str(key): str(value)
                for key, value in payload.items()
                if isinstance(key, str) and isinstance(value, str) and value.strip()
            }
    return overlays


TRANSLATION_OVERLAYS: dict[str, dict[str, str]] = _load_translation_overlays()


def _build_translation_catalogs() -> dict[str, dict[str, str]]:
    catalogs: dict[str, dict[str, str]] = {"en_US": dict(TRANSLATIONS_EN)}
    required = set(TRANSLATIONS_EN)
    for language in sorted(set(SUPPORTED_LANGUAGES) - {SOURCE_LANGUAGE, "en_US"}):
        overlay = TRANSLATION_OVERLAYS.get(language, {})
        missing = sorted(required - set(overlay))
        empty = sorted(key for key, value in overlay.items() if key in required and not value.strip())
        if missing or empty:
            detail_parts: list[str] = []
            if missing:
                detail_parts.append(f"missing={missing[:5]}")
            if empty:
                detail_parts.append(f"empty={empty[:5]}")
            raise RuntimeError(f"Incomplete locale catalog {language}: " + "; ".join(detail_parts))
        source_fallback = sorted(
            key
            for key in required
            if not is_translation_neutral(key)
            and overlay.get(key) == key
        )
        english_fallback = sorted(
            key
            for key in required
            if not is_translation_neutral(key)
            and any("\u4e00" <= ch <= "\u9fff" for ch in key)
            and overlay.get(key) == TRANSLATIONS_EN.get(key)
        )
        prefixed_fallback = sorted(
            key
            for key in required
            if _LANGUAGE_PREFIX_RE.match(str(overlay.get(key, "")))
        )
        if source_fallback or english_fallback or prefixed_fallback:
            detail_parts = []
            if source_fallback:
                detail_parts.append(f"source_fallback={source_fallback[:5]}")
            if english_fallback:
                detail_parts.append(f"english_fallback={english_fallback[:5]}")
            if prefixed_fallback:
                detail_parts.append(f"prefixed_fallback={prefixed_fallback[:5]}")
            raise RuntimeError(f"Locale catalog {language} contains fallback text: " + "; ".join(detail_parts))
        catalogs[language] = dict(overlay)
    return catalogs


