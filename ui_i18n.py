def is_translation_neutral(text: str) -> bool:
    candidate = str(text or "")
    stripped = candidate.strip()
    if candidate in PRODUCT_NAMES or stripped in PRODUCT_NAMES:
        return True
    if candidate in TRANSLATION_NEUTRAL_TEXTS or stripped in TRANSLATION_NEUTRAL_TEXTS:
        return True
    if not stripped:
        return True
    if _PLACEHOLDER_ONLY_RE.fullmatch(stripped):
        return True
    if "{" in stripped and _PLACEHOLDER_SYMBOLS_RE.fullmatch(_PLACEHOLDER_RE.sub("", stripped)):
        return True
    if _URL_OR_PATH_RE.match(stripped):
        return True
    if _EMAIL_LIST_RE.fullmatch(stripped):
        return True
    if _NUMERIC_OR_SYMBOL_RE.fullmatch(stripped):
        return True
    if _LOCALE_CODE_RE.fullmatch(stripped):
        return True
    if _TECH_TOKEN_RE.fullmatch(stripped):
        return True
    return False
